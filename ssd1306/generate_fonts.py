#!/usr/bin/env python3
"""Regenerates the bitmap-font glyph-data headers in this directory from the
source PNGs in fonts/.

Run with no arguments from anywhere (paths are relative to this script):

    python generate_fonts.py

Each fonts/<name>_<W>x<H>.png is a horizontal strip of glyph cells, W by H
pixels each, laid out left to right starting at ASCII 32 (space) - the cell
size is read straight from the filename, after the last '_'. Any number of
glyphs is fine (however many whole WxH cells fit the strip's width); nothing
requires the strip to reach any particular character. A glyph cell may
already bake in its own inter-character spacing as blank columns - that's a
per-font rendering choice made where the font is wired up
(ssd1306_draw_text()'s spacing_px / ssd1306_console_set_char_spacing()), not
here.

For each PNG this writes/overwrites <name>_<W>x<H>.h next to it (new PNGs
produce new headers; existing ones are always regenerated, so editing a PNG
and re-running picks up the change). Every write is round-trip verified -
the glyph data is decoded back into a bitmap and compared pixel-for-pixel
against the source before the header is trusted - and a few of the first
cells are printed as ASCII art so a bad crop/offset is obvious immediately
rather than discovered on hardware.

This only produces the glyph-data headers. Wiring a new one up as a public
ssd1306_font_t (in ssd1306.h/.c) is a separate, deliberate step - this
script doesn't guess a public name, first_code, or glyph_count for you.
"""

import os
import re
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("This script needs Pillow: python -m pip install Pillow")

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
FONTS_DIR = os.path.join(SCRIPT_DIR, "fonts")

FIRST_CODE = 32  # ' ' - fixed convention for every font strip in fonts/.
STEM_RE = re.compile(r"^(?P<name>.+)_(?P<w>\d+)x(?P<h>\d+)$")


def extract(png_path, cell_w, cell_h):
    im = Image.open(png_path).convert("L")
    width, height = im.size
    if height != cell_h:
        raise ValueError(f"image height {height} != cell height {cell_h}")
    if width % cell_w != 0:
        raise ValueError(f"image width {width} not a multiple of cell width {cell_w}")

    n_cells = width // cell_w
    bytes_per_col = (cell_h + 7) // 8
    px = im.load()

    data = []
    for i in range(n_cells):
        for col in range(cell_w):
            col_bytes = [0] * bytes_per_col
            for row in range(cell_h):
                if px[i * cell_w + col, row] > 128:
                    col_bytes[row // 8] |= 1 << (row % 8)
            data.extend(col_bytes)

    # Round-trip verify: decode `data` back into pixels and diff against the
    # source. Any mismatch means the extraction logic itself is wrong -
    # never trust generated glyph data without this.
    diffs = 0
    idx = 0
    for i in range(n_cells):
        for col in range(cell_w):
            col_bytes = data[idx:idx + bytes_per_col]
            idx += bytes_per_col
            for row in range(cell_h):
                bit = (col_bytes[row // 8] >> (row % 8)) & 1
                on = 1 if px[i * cell_w + col, row] > 128 else 0
                if bit != on:
                    diffs += 1
    if diffs:
        raise ValueError(f"round-trip verification failed: {diffs} pixel mismatches")

    return data, n_cells, px


def ascii_preview(px, cell_w, cell_h, cell_index, first_code):
    code = first_code + cell_index
    ch = chr(code) if 32 <= code < 127 else f"\\x{code:02x}"
    lines = [f"  cell {cell_index} (code {code} = {ch!r}):"]
    for y in range(cell_h):
        row = "".join("#" if px[cell_index * cell_w + x, y] > 128 else "." for x in range(cell_w))
        lines.append("    " + row)
    return "\n".join(lines)


def array_name(name, w, h):
    words = re.split(r"[_-]+", name)
    return "kFont" + "".join(w.capitalize() for w in words if w) + f"{w}x{h}"


def write_header(out_path, arr_name, name, w, h, n_cells, source_filename, data):
    body_lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        body_lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")

    last_code = FIRST_CODE + n_cells - 1
    comment = (
        f"// Generated by generate_fonts.py from fonts/{source_filename} - do not edit by\n"
        f"// hand, re-run the script instead.\n"
        f"// {w}x{h} glyphs, ASCII {FIRST_CODE} (' ') through {last_code} "
        f"({chr(last_code)!r} if printable) - {n_cells} glyphs."
    )

    with open(out_path, "w", newline="\n") as f:
        f.write("#pragma once\n\n")
        f.write(comment + "\n\n")
        f.write(f"static const unsigned char {arr_name}[] = {{\n")
        f.write("\n".join(body_lines) + "\n")
        f.write("};\n")


def main():
    if not os.path.isdir(FONTS_DIR):
        sys.exit(f"No fonts/ directory next to this script ({FONTS_DIR})")

    pngs = sorted(f for f in os.listdir(FONTS_DIR) if f.lower().endswith(".png"))
    if not pngs:
        print("No .png files found in fonts/.")
        return

    ok, failed = 0, 0
    for png_name in pngs:
        stem = os.path.splitext(png_name)[0]
        m = STEM_RE.match(stem)
        if not m:
            print(f"SKIP {png_name}: filename doesn't end in _<W>x<H>")
            failed += 1
            continue

        name = m.group("name")
        cell_w, cell_h = int(m.group("w")), int(m.group("h"))
        png_path = os.path.join(FONTS_DIR, png_name)

        try:
            data, n_cells, px = extract(png_path, cell_w, cell_h)
        except ValueError as e:
            print(f"FAIL {png_name}: {e}")
            failed += 1
            continue

        arr_name = array_name(name, cell_w, cell_h)
        out_path = os.path.join(SCRIPT_DIR, f"{stem}.h")
        write_header(out_path, arr_name, name, cell_w, cell_h, n_cells, png_name, data)

        print(f"OK   {png_name} -> {stem}.h  ({arr_name}, {n_cells} glyphs, "
              f"codes {FIRST_CODE}-{FIRST_CODE + n_cells - 1})")
        for i in range(min(3, n_cells)):
            print(ascii_preview(px, cell_w, cell_h, i, FIRST_CODE))
        ok += 1

    print(f"\n{ok} header(s) written, {failed} skipped/failed.")
    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
