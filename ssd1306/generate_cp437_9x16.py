# VGA repeats column 8 (0-indexed, i.e. the glyph's rightmost of its 8 real
# columns) into the 9th column for these codes only - the box-drawing/
# block range - so horizontal lines and box edges join seamlessly between
# adjacent character cells; every other glyph's 9th column is blank.
NINTH_COLUMN_REPEAT_RANGE = range(0xC0, 0xE0)  # 192-223


def widen_to_9px(rows_8px):
    """rows_8px: 16 bytes, one per row, bit 7 = leftmost of 8 columns.
    Returns a 9x16 list of lists of bools, cols[col][row]."""
    cols = [[False] * 16 for _ in range(9)]
    for row, byte in enumerate(rows_8px):
        for col in range(8):
            cols[col][row] = (byte & (0x80 >> col)) != 0
    return cols


def apply_ninth_column(cols, code):
    if code in NINTH_COLUMN_REPEAT_RANGE:
        cols[8] = list(cols[7])
    return cols


def pack_column_major(cols):
    """cols: 9 lists of 16 bools -> column-major bytes, 2 per column
    (bytes_per_col = ceil(16/8) = 2), matching ssd1306_font_t's storage."""
    data = []
    for col in cols:
        for byte_idx in range(2):
            b = 0
            for bit in range(8):
                row = byte_idx * 8 + bit
                if row < 16 and col[row]:
                    b |= 1 << bit
            data.append(b)
    return data


def unpack_column_major(data):
    """Inverse of pack_column_major(), for round-trip verification."""
    cols = []
    for col_idx in range(9):
        col = [False] * 16
        for byte_idx in range(2):
            b = data[col_idx * 2 + byte_idx]
            for bit in range(8):
                row = byte_idx * 8 + bit
                if row < 16:
                    col[row] = (b & (1 << bit)) != 0
        cols.append(col)
    return cols


def ascii_art(cols, code):
    ch = chr(code) if 32 <= code < 127 else f"\\x{code:02x}"
    lines = [f"  code {code} (0x{code:02X}) = {ch!r}:"]
    for row in range(16):
        line = "".join("#" if cols[c][row] else "." for c in range(9))
        lines.append("    " + line)
    return "\n".join(lines)


def main():
    if len(CP437_8X16) != 256:
        sys.exit(f"expected 256 source glyphs, got {len(CP437_8X16)}")

    all_data = []
    diffs = 0
    for code, rows_8px in enumerate(CP437_8X16):
        if len(rows_8px) != 16:
            sys.exit(f"code {code}: expected 16 rows, got {len(rows_8px)}")

        cols = widen_to_9px(rows_8px)
        cols = apply_ninth_column(cols, code)
        data = pack_column_major(cols)
        all_data.extend(data)

        # Round-trip: decode back and compare against the 9px bitmap we
        # just built (not the raw 8px source directly, since column 8 is a
        # deliberate addition with its own rule, not something the source
        # data has an opinion on).
        decoded = unpack_column_major(data)
        for c in range(9):
            for r in range(16):
                if decoded[c][r] != cols[c][r]:
                    diffs += 1

    print(f"Processed {len(CP437_8X16)} glyphs, 9x16 each, round-trip diffs={diffs}")
    if diffs:
        sys.exit("round-trip verification failed - not writing header")

    # A representative preview: a plain letter, the classic smiley (code
    # 1), and three box-drawing codes chosen to show the 9th-column join
    # in action (a horizontal line, a corner, and a T-junction).
    for code in (65, 1, 0xC4, 0xDA, 0xC3):
        cols = apply_ninth_column(widen_to_9px(CP437_8X16[code]), code)
        print(ascii_art(cols, code))

    out_path = __import__("os").path.join(SCRIPT_DIR, "cp437_9x16.h")
    lines = []
    for i in range(0, len(all_data), 16):
        chunk = all_data[i:i + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")

    header = f"""#pragma once

// Generated by generate_cp437_9x16.py - do not edit by hand, re-run the
// script instead (see its own module docstring for the full provenance
// and the VGA 9th-column rule this applies).
// The full IBM PC/VGA codepage 437, 9x16 glyphs, all 256 codes.
static const unsigned char kFontCp437_9x16[] = {{
{chr(10).join(lines)}
}};
"""
    with open(out_path, "w", newline="\n") as f:
        f.write(header)
    print(f"\nwrote {out_path}")


if __name__ == "__main__":
    main()
