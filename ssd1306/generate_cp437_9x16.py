#!/usr/bin/env python3
"""One-shot generator for cp437_9x16.h - the full 256-glyph IBM PC/VGA
codepage 437 font at its authentic 9x16 text-mode cell size.

Unlike generate_fonts.py (which extracts fonts from PNGs in fonts/), this
font isn't sourced from an image here - CP437_8X16 below is the classic
IBM VGA ROM font's 8x16 row-major bitmap data (one byte per row, bit 7 =
leftmost pixel), taken verbatim from the "Modern DOS 8x16" font bitmaps in
the pcface project (https://github.com/susam/pcface,
out/moderndos-8x16/fontlist.js), dual-licensed MIT / CC0 1.0 - the font
itself was created by Jayvee Enaguas and released under CC0 1.0.

Real VGA text mode renders CP437 in a 9-pixel-wide cell, not 8: for glyphs
132-223 (0x84-0xDF, box-drawing/block characters) the 9th column repeats
column 8's own pixel so horizontal lines/box edges join up seamlessly
across adjacent character cells; every other glyph's 9th column is left
blank. That's the "real" 9x16 CP437 this script produces - not just the
8x16 data padded with a blank column - see widen_to_9px() below.

Run with no arguments from anywhere (paths are relative to this script):

    python generate_cp437_9x16.py

Round-trip verifies the widened 9x16 bitmap against CP437_8X16 before
writing cp437_9x16.h, and prints ASCII art for a handful of glyphs
(including box-drawing ones, to make the 9th-column join visible) as a
sanity check.
"""

